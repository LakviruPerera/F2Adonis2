#' Benchmark Runtime Performance of the modified F2 Statistic Across Operating Systems
#'
#' @description
#' An execution profiling utility designed to check and record calculation runtime metrics for the modified
#' F2 test. It simulates a high-dimensional omics expression array to evaluate local system
#' computation limits, matrix allocation speeds, and multithreading overhead across Windows and macOS platforms.
#'
#' @details
#' Because the modified F2 algorithm avoids pooling variance and dynamically maps unpooled group-specific
#' distance segments across every individual permutation loop, computational speeds vary based on active
#' background architectures:
#'
#' \strong{macOS (UNIX Backends):} Utilizes unified memory maps. Multi-core operations leverage fork-based
#' threading layouts (type = "FORK") which operate instantaneously without duplication overhead.
#'
#' \strong{Windows (Socket Backends):} Requires background network sockets (type = "PSOCK"). This architecture
#' clones the complete global workspace onto every independent engine thread, adding a minor initial configuration lag.
#'
#' \strong{Computational Performance & Reference Benchmarks:}
#'
#' For practical reference, a baseline profiling run consisting of a generated high-dimensional matrix
#' (\code{n_samples = 30}, \code{n_features = 10000}) evaluated across 999 permutations
#' using single-core sequential execution (\code{cores = 1}) yields the following
#' benchmark profiles. The simulated data points are sampled from a standard normal distribution
#' with a mean (\eqn{\mu}) of 0 and a variance (\eqn{\sigma^2}) of 1:
#'
#' \bold{Windows 11 Reference System (High-End AMD AI Architecture):}
#' \itemize{
#'   \item \bold{Processor Spec:} AMD Ryzen AI 9 365 (Base clock @ 2.00 GHz)
#'   \item \bold{System Type:} 64-bit OS, x64-based processor
#'   \item \bold{Installed Memory:} 32.0 GB RAM
#'   \item \bold{Total Runtime Speed:} 12.59 seconds
#'   \item \bold{Calculation Velocity:} 79.4 loops/second
#' }
#'
#' \bold{macOS Reference System:}
#' \itemize{
#'   \item \bold{Processor Spec:} Apple Silicon M-Series (Unified Memory Architecture)
#'   \item \bold{Total Runtime Speed:} Approximately 6.0 to 8.0 seconds
#'   \item \bold{Calculation Velocity:} ~125.0 to 165.0 loops/second
#' }
#'
#' @param n_samples An integer specifying the total number of experimental samples (rows) to generate. Default is 30.
#' @param n_features An integer specifying the total number of high-dimensional metabolic peaks or features (columns) to simulate. Default is 5000.
#' @param permutations An integer defining the number of labels shuffling iterations to evaluate for empirical calibration. Default is 999.
#' @param cores An integer detailing the number of CPU processing cores to utilize for evaluation. Default is 1.
#'
#' @return An object of class \code{F2_adonis2} containing the calculated variance breakdown array, with processing speed metadata logged directly to the system console.
#'
#' @note For large datasets, passing precomputed distance structures generated by \code{vegdist()} directly to the model formula is strongly recommended to eliminate repeated high-dimensional vector array partitioning.
#'
#' @author Lakviru Perera \email{korathotagelaperera@@montana.edu}
#'
#' @references
#' Anderson, M.J., Walsh, D.C.I., Robert Clarke, K., Gorley, R.N. and Guerra-Castro, E. (2017), Some solutions to the multivariate Behrens–Fisher problem for dissimilarity-based analyses. Aust. N. Z. J. Stat., 59: 57-79.
#'
#' @examples
#' \dontrun{
#' # Run a standard single-core baseline check
#' benchmark_f2(n_samples = 30, n_features = 2000, permutations = 199)
#'
#' # Evaluate multi-core multi-threaded processing speeds across backends
#' benchmark_f2(n_samples = 40, n_features = 5000, permutations = 999, cores = 2)
#' }
#' @export
benchmark_f2 <- function(n_samples = 30, n_features = 5000, permutations = 999, cores = 1) {

  os_type <- Sys.info()["sysname"]
  cat("=== F2Adonis2 Computing Performance Profile ===\n")
  cat("Platform Architecture Identified:", os_type, "\n")
  cat("Simulating Matrix Dimensions:   ", n_samples, "samples x", n_features, "features\n\n")

  set.seed(42)
  mock_data <- matrix(stats::rnorm(n_samples * n_features), nrow = n_samples, ncol = n_features)
  mock_design <- data.frame(Group = factor(rep(c("Control", "Disease_A", "Disease_B"), length.out = n_samples)))

  if (cores > 1) {
    if (os_type == "Windows") {
      cat("Configuring background Socket Cluster Nodes (PSOCK) for Windows...\n")
      cl <- parallel::makeCluster(cores, type = "PSOCK")
      parallel::clusterEvalQ(cl, library(vegan))
    } else {
      cat("Launching active Fork-based Threading Nodes (FORK) for UNIX/macOS...\n")
      cl <- parallel::makeCluster(cores, type = "FORK")
    }
    on.exit(parallel::stopCluster(cl))
  }

  start_time <- Sys.time()
  fit <- F2_adonis2(mock_data ~ Group, data = mock_design, method = "euclidean",
                    permutations = permutations,
                    bootstrap = TRUE,
                    bias.adjust = TRUE)
  end_time <- Sys.time()
  elapsed <- as.numeric(difftime(end_time, start_time, units = "secs"))

  cat("\n--- Evaluation Processing Times ---\n")
  cat("Total Runtime Speed: ", round(elapsed, 2), " seconds\n", sep = "")
  cat("Calculation Velocity: ", round((permutations + 1) / elapsed, 1), " loops/sec\n")
  cat("------------------------------------\n")

  return(fit)
}

